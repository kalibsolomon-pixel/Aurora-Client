"""Regenerate docs/FAIR_PLAY.md from feature/FeatureCatalog.java.

Run from the repository root after changing a feature's fair-play class or
note:  python tools/gen_fair_play_doc.py
FeatureCatalogTest fails when the document and the catalog disagree.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / 'core/src/main/java/com/aurora/client/feature/FeatureCatalog.java'
DOC = ROOT / 'docs/FAIR_PLAY.md'

TEMPLATE = '''# Fair play

This page is for server owners and for players who want to know what Aurora Client does. An automated test checks it against the code, so it cannot drift from what ships. Edit the notes in `FeatureCatalog.java` and regenerate with `python tools/gen_fair_play_doc.py`; do not edit this file by hand.

## What Aurora never does

- It sends no custom packets and registers no plugin channels.
- It does not change the client's tick rate or the timing of anything sent to the server.
- It collects and sends no telemetry.

The whole mod has two places that send anything to a server. Both are in Better Hitreg, on keys that are unbound until the player binds them: Switch Hand changes the vanilla Main Hand option (the same packet as changing it in Options), and the practice scoreboard's Send key posts the score as an ordinary chat message.

## Classes

| Class | Meaning |
|---|---|
%(classes)s

## Off in a fresh install

A new install has these off. A player has to turn each one on.

- FreeLook
- Entity Health, which shows the health of mobs; showing other players' health is a second switch, also off
- Other players' totem pop counts, on the HUD and on nametags
- Dots for other players on the minimap
- Full Bright, which raises brightness past the vanilla maximum
- No Fog, which pushes distance fog back
- Water and lava clarity (Pack Tweaks)
- Better Hitreg, and inside it the reach rings, extra hitboxes and hiding of other fights

Changing a default does not change an existing install: a player who already had one of these on keeps it on.

## On in a fresh install, and worth knowing

- Hitboxes are drawn, as vanilla's F3+B draws them.

## Every feature

| Feature | Class | What it does |
|---|---|---|
%(rows)s
'''


def main():
    source = CATALOG.read_text(encoding='utf-8')
    classes = re.findall(r'^\s+([A-Z_]+)\("([^"]+)",\s*"([^"]+)"\)[,;]', source, re.M)
    labels = {name: label for name, label, _ in classes}
    names = dict(re.findall(r'module\("([^"]+)", "([^"]+)",', source)
                 + re.findall(r'setting\("([^"]+)", "([^"]+)"\)', source))
    rows = ['| %s | %s | %s |' % (names[fid], labels[cls], note)
            for fid, cls, note in re.findall(r'classify\("([^"]+)", FairPlay\.(\w+), "([^"]*)"', source)]
    text = TEMPLATE % dict(classes='\n'.join('| %s | %s |' % (label, meaning) for _, label, meaning in classes),
                           rows='\n'.join(rows))
    DOC.write_text(text, encoding='utf-8', newline='\n')
    print('wrote', DOC.relative_to(ROOT), 'with', len(rows), 'features')


if __name__ == '__main__':
    main()
